function translate(source, values = {}) {
  const template = document.documentElement.lang === "ar" ? (arabic[source] ?? source) : source;
  return template.replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? ""));
}

function setInterfaceLanguage(language) {
  const selected = language === "ar" ? "ar" : "en";
  document.documentElement.lang = selected;
  document.documentElement.dir = selected === "ar" ? "rtl" : "ltr";
  localStorage.setItem("image-seo-interface-language", selected);
  document.querySelectorAll("[data-i18n]").forEach(element => {
    element.textContent = translate(element.dataset.i18n);
  });
  for (const [attribute, property] of [["placeholder", "placeholder"], ["aria", "aria-label"], ["title", "title"]]) {
    document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(element => {
      element.setAttribute(property, translate(element.dataset[`i18n${attribute[0].toUpperCase()}${attribute.slice(1)}`]));
    });
  }
  document.querySelectorAll("[data-interface-language]").forEach(button => {
    button.setAttribute("aria-pressed", String(button.dataset.interfaceLanguage === selected));
  });
  document.dispatchEvent(new CustomEvent("image-seo:language-change"));
}

function userMessage(source, fallback) {
  if (document.documentElement.lang !== "ar") return source || fallback;
  return arabic[source] || translate(fallback);
}

window.imageSeoI18n = { t: translate, userMessage, setLanguage: setInterfaceLanguage };
document.querySelectorAll("[data-interface-language]").forEach(button => {
  button.addEventListener("click", () => setInterfaceLanguage(button.dataset.interfaceLanguage));
});
setInterfaceLanguage(localStorage.getItem("image-seo-interface-language") || "ar");
